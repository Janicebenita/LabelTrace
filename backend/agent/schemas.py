from typing import Annotated, Literal
from pydantic import BaseModel, ConfigDict, Field, StringConstraints

LABEL_KEY = r"^[A-Za-z0-9_.\-]{1,60}$"
Status = Literal["READY", "BLOCKED", "REVIEW REQUIRED", "UNKNOWN"]
Severity = Literal["info", "low", "medium", "high", "critical"]
Classification = Literal["deterministic", "ai_advisory", "insufficient_evidence", "human_review"]
Short = Annotated[str, StringConstraints(max_length=400)]
Label = Annotated[str, StringConstraints(max_length=60)]

class AgentRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    question: str = Field(min_length=3, max_length=1000)
    label_key: str | None = Field(default=None, pattern=LABEL_KEY)

# --- What the model may submit (it can never set release_status or fabricate evidence records) ---
class SubmittedFinding(BaseModel):
    model_config = ConfigDict(extra="forbid")
    id: str = Field(max_length=20, description="Short finding id such as F1")
    severity: Severity
    explanation: str = Field(max_length=1200)
    evidence_ids: list[Annotated[str, StringConstraints(max_length=12)]] = Field(max_length=12, description="Evidence ids (E1, E2...) returned by tools")
    classification: Classification
    recommended_action: str = Field(max_length=600)

class ReportSubmission(BaseModel):
    model_config = ConfigDict(extra="forbid")
    summary: str = Field(min_length=1, max_length=1500)
    affected_variants: list[Label] = Field(default_factory=list, max_length=8)
    findings: list[SubmittedFinding] = Field(default_factory=list, max_length=12)
    recommended_actions: list[Short] = Field(default_factory=list, max_length=10)
    limitations: list[Short] = Field(default_factory=list, max_length=8)

# --- Validated response returned to the UI ---
class Finding(BaseModel):
    id: str
    severity: Severity
    explanation: str
    evidence_ids: list[str]
    classification: Classification
    recommended_action: str

class EvidenceItem(BaseModel):
    id: str
    kind: str
    record_id: str
    summary: str
    tool: str
    cited_by: list[str] = Field(default_factory=list)

class LabelGate(BaseModel):
    label_key: str
    status: Status
    blockers: list[str] = Field(default_factory=list)
    pending_human_actions: list[str] = Field(default_factory=list)
    workflow_state: str | None = None
    released: bool = False
    revision_id: str | None = None

class ToolActivity(BaseModel):
    step: int
    tool: str
    args: dict
    ok: bool
    evidence_ids: list[str] = Field(default_factory=list)
    elapsed_ms: float = 0
    error: str | None = None

class AgentResponse(BaseModel):
    request_id: str
    run_id: str | None = None
    mode: Literal["claude", "deterministic"]
    model: str | None = None
    summary: str
    release_status: Status
    label_statuses: list[LabelGate] = Field(default_factory=list)
    affected_variants: list[str] = Field(default_factory=list)
    findings: list[Finding] = Field(default_factory=list)
    evidence: list[EvidenceItem] = Field(default_factory=list)
    recommended_actions: list[str] = Field(default_factory=list)
    limitations: list[str] = Field(default_factory=list)
    human_review_required: bool = True
    tool_activity: list[ToolActivity] = Field(default_factory=list)
    plans: list[dict] = Field(default_factory=list, description="Deterministic remediation plans, generated by code")
